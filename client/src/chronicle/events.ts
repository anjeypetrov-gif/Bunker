export interface Req { pro?: string[]; bag?: string[] }
export interface Outcome {
  text: string;
  d?: Partial<Res>;
  hurt?: number;        // урон жителю {A}
  hurtAll?: number;     // урон всем
  heal?: number;        // лечение всем
  kill?: 'A';           // {A} погибает
  join?: boolean;       // в бункер попадает новый житель
  set?: string;         // флаг для цепочек событий
}
export interface Choice {
  label: string;
  req?: Req;            // без этого навыка вариант закрыт
  reqText?: string;
  boost?: Req;          // навык повышает шанс
  p?: number;           // шанс успеха (если не указан — всегда успех)
  win: Outcome;
  lose?: Outcome;
}
